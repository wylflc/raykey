def roe_ss(p):
    nii = p["nim"] * IEA_RATIO
    rev = nii + p["nonii"]
    opex = rev * p["cir"]
    ppop = rev - opex
    imp = p["cc"] * LOAN_RATIO + p["oth"]
    pbt = ppop - imp
    roa_c = pbt * (1 - TAX_EFF) - PERP_COST
    return roa_c * p["lev"], dict(nii=nii, rev=rev, opex=opex, ppop=ppop, imp=imp, pbt=pbt, roa=roa_c)


def ri_value(b0, roes, coe, g, payout, roe_lt):
    """剩余收益模型，显式期 10 年；同时返回股利折现结果（干净盈余下两者相等）。"""
    b, pv_ri, divs = b0, 0.0, []
    for t, (r, d) in enumerate(zip(roes, payout), 1):
        e = r * b
        pv_ri += (r - coe) * b / (1 + coe) ** t
        divs.append(d * e)
        b += e - d * e
    pb_t = (roe_lt - g) / (coe - g)
    v_ri = b0 + pv_ri + (pb_t - 1) * b / (1 + coe) ** len(roes)
    v_ddm = sum(dv / (1 + coe) ** t for t, dv in enumerate(divs, 1)) + pb_t * b / (1 + coe) ** len(roes)
    return v_ri, v_ddm, b, pb_t, divs


def irr(price, divs, terminal):
    f = lambda r: sum(d / (1 + r) ** t for t, d in enumerate(divs, 1)) + terminal / (1 + r) ** len(divs) - price
    return bisect(f, -0.5, 1.0)


